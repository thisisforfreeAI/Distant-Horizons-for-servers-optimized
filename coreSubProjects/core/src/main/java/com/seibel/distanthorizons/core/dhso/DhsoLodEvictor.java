package com.seibel.distanthorizons.core.dhso;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.Collections;
import java.util.HashSet;
import java.util.List;
import java.util.PriorityQueue;
import java.util.Set;

/**
 * Picks and deletes rebuildable LOD data from one DH database. <br><br>
 *
 * Why this is safe: <br>
 * - Only fine detail rows ({@code FullData.DetailLevel <= maxEvictableDetailLevel}) are deleted.
 *   Coarser ancestors are kept, so distant terrain stays visible at lower detail. <br>
 * - DH builds parents incrementally (each changed child is merged into its parent),
 *   so a missing child doesn't erase anything from its parent. <br>
 * - Rows that still have pending propagation or regeneration work
 *   ({@code ApplyToParent}, {@code ApplyToChildren}, {@code Regenerate}) are skipped. <br>
 * - A missing section is regenerated by DH's normal request handling when a client asks for it. <br>
 * - The matching {@code ChunkHash} rows are deleted in the same transaction, so DH
 *   doesn't skip rebuilding those sections the next time their chunks load. <br>
 * - Each batch is one transaction, so a crash leaves either the old or the new state. <br><br>
 *
 * Eviction order: farthest from every online player first. Sections inside
 * {@code protectedRadiusBlocks} of a player are never picked.
 */
public class DhsoLodEvictor
{
	/** a level 0 (full detail) section is 64 blocks wide, each level up doubles it */
	public static final int LEVEL_ZERO_SECTION_WIDTH_IN_BLOCKS_LOG2 = 6;



	/** a FullData primary key */
	public static class SectionKey
	{
		public final int detailLevel;
		public final int posX;
		public final int posZ;
		/** distance in blocks from the section's center to the nearest protected point */
		public final double distance;

		public SectionKey(int detailLevel, int posX, int posZ, double distance)
		{
			this.detailLevel = detailLevel;
			this.posX = posX;
			this.posZ = posZ;
			this.distance = distance;
		}

		public int widthInBlocks() { return 1 << (LEVEL_ZERO_SECTION_WIDTH_IN_BLOCKS_LOG2 + this.detailLevel); }
		public int minBlockX() { return this.posX * this.widthInBlocks(); }
		public int minBlockZ() { return this.posZ * this.widthInBlocks(); }

		@Override
		public String toString() { return "[" + this.detailLevel + "," + this.posX + "," + this.posZ + "]"; }
	}

	/** an x/z block position to protect */
	public static class ProtectedPoint
	{
		public final double blockX;
		public final double blockZ;
		public ProtectedPoint(double blockX, double blockZ) { this.blockX = blockX; this.blockZ = blockZ; }
	}



	//==================//
	// size measurement //
	//==================//

	/**
	 * @return the bytes used by live data, excluding free pages. <br>
	 * This is what the budgets are compared against: deleting rows frees pages
	 * inside the file (which new LODs reuse) without shrinking the file itself.
	 */
	public static long getUsedBytes(Connection connection) throws SQLException
	{
		long pageSize = queryLong(connection, "PRAGMA page_size;");
		long pageCount = queryLong(connection, "PRAGMA page_count;");
		long freePageCount = queryLong(connection, "PRAGMA freelist_count;");
		return (pageCount - freePageCount) * pageSize;
	}

	private static long queryLong(Connection connection, String sql) throws SQLException
	{
		try (Statement statement = connection.createStatement();
			ResultSet resultSet = statement.executeQuery(sql))
		{
			return resultSet.next() ? resultSet.getLong(1) : 0;
		}
	}



	//===========//
	// selection //
	//===========//

	/**
	 * Returns up to {@code maxCount} evictable sections, farthest from every protected point first. <br>
	 * Only reads the primary key index and the small partial flag indexes, not the LOD data itself.
	 */
	public static List<SectionKey> selectCandidates(
			Connection connection, List<ProtectedPoint> protectedPoints,
			int maxEvictableDetailLevel, int protectedRadiusBlocks, int maxCount) throws SQLException
	{
		Set<Long> busyKeys = getKeysWithPendingWork(connection, maxEvictableDetailLevel);

		// min-heap on distance so the closest candidate is dropped when the heap is full
		PriorityQueue<SectionKey> farthest = new PriorityQueue<>(Math.max(1, Math.min(maxCount, 10_000)), (a, b) -> Double.compare(a.distance, b.distance));

		try (PreparedStatement statement = connection.prepareStatement(
				"SELECT DetailLevel, PosX, PosZ FROM FullData WHERE DetailLevel <= ?;"))
		{
			statement.setInt(1, maxEvictableDetailLevel);
			try (ResultSet resultSet = statement.executeQuery())
			{
				while (resultSet.next())
				{
					int detailLevel = resultSet.getInt(1);
					int posX = resultSet.getInt(2);
					int posZ = resultSet.getInt(3);
					if (busyKeys.contains(packKey(detailLevel, posX, posZ)))
					{
						continue;
					}

					double distance = distanceToNearest(detailLevel, posX, posZ, protectedPoints);
					if (distance <= protectedRadiusBlocks)
					{
						continue;
					}

					if (farthest.size() < maxCount)
					{
						farthest.add(new SectionKey(detailLevel, posX, posZ, distance));
					}
					else if (!farthest.isEmpty() && farthest.peek().distance < distance)
					{
						farthest.poll();
						farthest.add(new SectionKey(detailLevel, posX, posZ, distance));
					}
				}
			}
		}

		ArrayList<SectionKey> result = new ArrayList<>(farthest);
		// farthest first
		Collections.sort(result, (a, b) -> Double.compare(b.distance, a.distance));
		return result;
	}

	/** @return the distance from the section's center to the closest protected point, or {@link Double#MAX_VALUE} if there are none */
	public static double distanceToNearest(int detailLevel, int posX, int posZ, List<ProtectedPoint> protectedPoints)
	{
		double width = 1 << (LEVEL_ZERO_SECTION_WIDTH_IN_BLOCKS_LOG2 + detailLevel);
		double centerX = (posX * width) + (width / 2.0);
		double centerZ = (posZ * width) + (width / 2.0);

		double minDistanceSquared = Double.MAX_VALUE;
		for (ProtectedPoint point : protectedPoints)
		{
			double dx = point.blockX - centerX;
			double dz = point.blockZ - centerZ;
			minDistanceSquared = Math.min(minDistanceSquared, (dx * dx) + (dz * dz));
		}
		return (minDistanceSquared == Double.MAX_VALUE) ? Double.MAX_VALUE : Math.sqrt(minDistanceSquared);
	}

	private static Set<Long> getKeysWithPendingWork(Connection connection, int maxEvictableDetailLevel) throws SQLException
	{
		HashSet<Long> keys = new HashSet<>();
		// each of these columns has a partial index on "= 1", so these are cheap
		String[] columns = { "ApplyToParent", "ApplyToChildren", "Regenerate" };
		for (String column : columns)
		{
			try (PreparedStatement statement = connection.prepareStatement(
					"SELECT DetailLevel, PosX, PosZ FROM FullData WHERE " + column + " = 1;");
				ResultSet resultSet = statement.executeQuery())
			{
				while (resultSet.next())
				{
					int detailLevel = resultSet.getInt(1);
					if (detailLevel <= maxEvictableDetailLevel)
					{
						keys.add(packKey(detailLevel, resultSet.getInt(2), resultSet.getInt(3)));
					}
				}
			}
		}
		return keys;
	}

	private static long packKey(int detailLevel, int posX, int posZ)
	{
		// detail level fits in 4 bits, positions in 30 bits each for any realistic world
		return ((long) (detailLevel & 0xF) << 60)
				| (((long) posX & 0x3FFFFFFFL) << 30)
				| ((long) posZ & 0x3FFFFFFFL);
	}



	//==========//
	// deletion //
	//==========//

	/**
	 * Deletes the given sections and their chunk hashes in one transaction.
	 * @return the number of LOD sections deleted
	 */
	public static int deleteSections(Connection connection, List<SectionKey> sections) throws SQLException
	{
		if (sections.isEmpty())
		{
			return 0;
		}

		boolean previousAutoCommit = connection.getAutoCommit();
		connection.setAutoCommit(false);
		int deletedCount = 0;
		try (PreparedStatement deleteLod = connection.prepareStatement(
				"DELETE FROM FullData WHERE DetailLevel = ? AND PosX = ? AND PosZ = ? " +
				// re-check the flags in case DH started working on this section after it was selected
				"AND IFNULL(ApplyToParent, 0) = 0 AND IFNULL(ApplyToChildren, 0) = 0 AND IFNULL(Regenerate, 0) = 0;");
			PreparedStatement deleteHashes = connection.prepareStatement(
				"DELETE FROM ChunkHash WHERE ChunkPosX BETWEEN ? AND ? AND ChunkPosZ BETWEEN ? AND ?;"))
		{
			for (SectionKey section : sections)
			{
				deleteLod.setInt(1, section.detailLevel);
				deleteLod.setInt(2, section.posX);
				deleteLod.setInt(3, section.posZ);
				int rows = deleteLod.executeUpdate();
				if (rows == 0)
				{
					continue;
				}
				deletedCount += rows;

				// a chunk is 16 blocks wide
				int minChunkX = section.minBlockX() >> 4;
				int minChunkZ = section.minBlockZ() >> 4;
				int widthInChunks = section.widthInBlocks() >> 4;
				deleteHashes.setInt(1, minChunkX);
				deleteHashes.setInt(2, minChunkX + widthInChunks - 1);
				deleteHashes.setInt(3, minChunkZ);
				deleteHashes.setInt(4, minChunkZ + widthInChunks - 1);
				deleteHashes.executeUpdate();
			}

			connection.commit();
			return deletedCount;
		}
		catch (SQLException | RuntimeException e)
		{
			connection.rollback();
			throw e;
		}
		finally
		{
			connection.setAutoCommit(previousAutoCommit);
		}
	}

	/** lets SQLite move committed pages from the WAL back into the database without blocking anyone */
	public static void passiveCheckpoint(Connection connection) throws SQLException
	{
		try (Statement statement = connection.createStatement())
		{
			statement.execute("PRAGMA wal_checkpoint(PASSIVE);");
		}
	}

}
